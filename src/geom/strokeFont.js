const TR = { 'Ç': 'C', 'Ğ': 'G', 'İ': 'I', 'Ö': 'O', 'Ş': 'S', 'Ü': 'U', 'ç': 'C', 'ğ': 'G', 'ı': 'I', 'ö': 'O', 'ş': 'S', 'ü': 'U' };

export function normText(s) { return [...String(s)].map(ch => TR[ch] ?? ch.toUpperCase()).join(''); }

/** Metni çizgilere çevir: yükseklik h (mm), karakter aralığı 6/4 genişlik. Dönüş: [[{x,y}...], ...] (x yazı yönü, y yükseklik), toplam genişlik */
export function textStrokes(text, h) {
  const k = h / 6, adv = 5.5 * k;
  const strokes = [];
  let x0 = 0;
  for (const ch of normText(text)) {
    const g = G[ch];
    if (g) for (const st of g.split('|')) strokes.push(st.trim().split(/\s+/).map(p => { const [x, y] = p.split(',').map(Number); return { x: x0 + x * k, y: y * k }; }));
    x0 += adv;
  }
  return { strokes, width: Math.max(0, x0 - 1.5 * k) };
}

export function unsupportedChars(text) { return [...new Set([...normText(text)].filter(ch => ch !== ' ' && !G[ch]))]; }
